"""Generate the Manual-Dex diagram-to-BOM part register without copying material claims."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def callout(kind, number):
    if number >= 200:
        return "—"
    if number >= 100:
        return str({101: 6, 102: 7 if kind == "hand" else 12,
                    103: 9, 104: 10, 105: 11, 106: 11, 107: 11}[number]).zfill(2)
    if kind == "hand":
        groups = {1: [1, 2], 2: [3, 5, 7], 3: [4, 6, 8], 4: [9, 10, 11],
                  5: [12], 8: [13], 9: [16, 17], 11: [18, 19, 20], 12: [14, 15]}
    else:
        groups = {1: [1, 2], 2: [3, 5, 7], 3: [4, 6, 8], 4: [9], 5: [10],
                  7: list(range(11, 16)), 8: list(range(16, 30)),
                  9: [32, 33], 11: [34, 35, 36], 12: [30, 31]}
    return next(f"{k:02d}" for k, values in groups.items() if number in values)


def generate():
    with (ROOT / "bom/rename_map.csv").open(newline="") as stream:
        naming = {row["current_cad_name"]: row["proposed_name"] for row in csv.DictReader(stream)}
    lines = ["# Manual-Dex component and material register", "",
             "Generated by `python tools/visualization/register.py` from the BOM CSVs and naming map.", "",
             "Numbers match the component-family callouts in the paired MuJoCo animation (G: glove, H: hand). Repeated parts",
             "share a callout; each individual BOM item and its material specification is listed here.",
             "A dash indicates a BOM item not represented in the CAD visualization. Quantities,",
             "unresolved specifications, and source-component names are preserved from the BOM.", ""]
    for kind, file in (("glove", "glove.csv"), ("hand", "robot_hand.csv")):
        lines += [f"## Manual-Dex {kind}", "",
                  "| Label | BOM ID | Qty | Component / release file | Material or specification | Function / status |",
                  "|---|---|---|---|---|---|"]
        with (ROOT / "bom" / file).open(newline="") as stream:
            for row in csv.DictReader(stream):
                number = int(row["id"].split("-")[1])
                part = row["part"]
                if row["make_buy"] == "make":
                    release = naming[part]
                    folder = "common" if release.startswith("cm_") else "glove" if release.startswith("gl_") else "robot_hand"
                    path = f"../../hardware/{folder}/stl/{release}.stl"
                    if not (ROOT / "docs/visualization" / path).resolve().is_file():
                        raise FileNotFoundError(path)
                    part = f"[{release}]({path})"
                notes = row["notes"] or f"{row['category']}; {row['subsystem']}"
                values = [callout(kind, number), row["id"], row["qty"], part,
                          row["material_spec"], f"{notes} ({row['status']})"]
                lines.append("| " + " | ".join(v.replace("|", "\\|").replace("\n", " ") for v in values) + " |")
        lines.append("")
    destination = ROOT / "docs/visualization/PARTS.md"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {destination}")


if __name__ == "__main__":
    generate()
